// scripts/build-quote-review-sql.cjs
//
// Turns the reviewed sheets in data/review/ into one SQL migration, so the
// database change is generated from exactly what was approved rather than
// typed by hand.
//
//   node scripts/build-quote-review-sql.cjs > supabase/migrations/<date>_quote_review.sql
//
// The migration:
//   1. copies quotes.approved_quotes to a backup table first (RLS on, no
//      access from the browser keys), so every change can be undone;
//   2. corrects authors (and, for four quotes, wording) from
//      attribution-review.csv;
//   3. moves quotes between topics from retag-existing.csv;
//   4. adds the quotes in new-quotes-proposed.csv, skipping any that
//      already exist.
// Every statement matches on exact text, so a quote edited since the review
// is simply left alone.

const fs = require("fs");
const path = require("path");

function parseCsv(file) {
  const src = fs.readFileSync(path.join(__dirname, "..", "data", "review", file), "utf8").replace(/^﻿/, "");
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (q) {
      if (ch === '"' && src[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && src[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.some((c) => c !== "")) rows.push(row);
      row = [];
    } else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const attribution = parseCsv("attribution-review.csv");
const retag = parseCsv("retag-existing.csv");
const added = parseCsv("new-quotes-proposed.csv");

const out = [];
const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, "");
const backup = `quotes.approved_quotes_backup_${stamp}`;

out.push(`-- Quote review: attribution fixes, topic moves and new quotes.`);
out.push(`-- Generated by scripts/build-quote-review-sql.cjs from data/review/*.csv.`);
out.push(`-- ${attribution.length} attribution fixes, ${retag.length} topic moves, ${added.length} new quotes.`);
out.push(`--`);
out.push(`-- To undo everything:`);
out.push(`--   begin;`);
out.push(`--   delete from quotes.approved_quotes where id not in (select id from ${backup});`);
out.push(`--   update quotes.approved_quotes a set text = b.text, author = b.author, category = b.category`);
out.push(`--     from ${backup} b where a.id = b.id;`);
out.push(`--   commit;`);
out.push(``);
out.push(`begin;`);
out.push(``);
out.push(`-- 1. Backup. The quotes schema grants table access to the browser keys by`);
out.push(`--    default, so lock this copy down: RLS on, no policies, no grants.`);
out.push(`create table ${backup} as table quotes.approved_quotes;`);
out.push(`alter table ${backup} enable row level security;`);
out.push(`revoke all on ${backup} from anon, authenticated;`);
out.push(``);
out.push(`-- 2. Attribution fixes`);
for (const r of attribution) {
  const sets = [];
  if (r.suggested_author && r.suggested_author !== r.current_author) sets.push(`author = ${lit(r.suggested_author)}`);
  if (r.suggested_text_change) sets.push(`text = ${lit(r.suggested_text_change)}`);
  if (!sets.length) continue;
  out.push(`update quotes.approved_quotes set ${sets.join(", ")}`);
  out.push(`  where author = ${lit(r.current_author)} and text = ${lit(r.quote)};`);
}
out.push(``);
out.push(`-- 3. Topic moves (matched on the corrected author where step 2 changed it)`);
for (const r of retag) {
  out.push(`update quotes.approved_quotes set category = ${lit(r.new_category)}`);
  out.push(`  where text = ${lit(r.quote)} and category = ${lit(r.current_category)};`);
}
out.push(``);
out.push(`-- 4. New quotes`);
for (const r of added) {
  out.push(`insert into quotes.approved_quotes (text, author, category)`);
  out.push(`  select ${lit(r.quote)}, ${lit(r.author)}, ${lit(r.category)}`);
  out.push(`  where not exists (select 1 from quotes.approved_quotes where text = ${lit(r.quote)});`);
}
out.push(``);
out.push(`commit;`);

process.stdout.write(out.join("\n") + "\n");
